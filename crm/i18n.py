def translator(language: str):
    """Returns `t(key, **values)` for the chosen language."""
    texts = TEXTS.get(language, TEXTS[DEFAULT_LANGUAGE])
    fallback = TEXTS[DEFAULT_LANGUAGE]

    def t(key: str, **values: object) -> str:
        text = texts.get(key) or fallback.get(key) or key
        return text.format(**values) if values else text

    return t
